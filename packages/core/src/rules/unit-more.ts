      explain:
        "한자어 수사도 수관형사이므로 단위 명사와 띄어 씁니다 — '삼십 분, 삼 개월, 이만 원'. 다만 '구분(區分)·십분(부사)·만원(滿員)'처럼 한 음절 수사는 다른 낱말과 문자열이 겹치므로, '개월'을 뺀 단위에서는 두 음절 이상의 수 표현만 고쳐 드립니다.",
