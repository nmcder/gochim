/**
 * 규정이 **허용**하지만 원칙과는 다른 표기.
 *
 * 이 파일의 규칙은 전부 `severity: 'warning'`이다. 틀린 글이 아니기 때문이다.
 * 겹말 규칙([redundancy.ts](./redundancy.ts))과 같은 자리에 선다 —
 * 고칠지 말지는 쓰는 사람이 정하고, 고침은 원칙이 무엇인지만 알려 준다.
 *
 * 오류로 세우지 않는 이유는 하나다. **정밀도 1.000은 "맞는 글에 밑줄을 긋지 않는다"는 약속**이고,
 * 규정이 허용하는 표기에 오류 밑줄을 그으면 그 약속이 깨진다.
 * 그렇다고 아무 말도 하지 않으면 원칙대로 쓰고 싶은 사람이 알 길이 없다. 그래서 경고다.
 *
 * 세 갈래를 담는다.
 *
 *  - **제46항** — 단음절 단어가 이어지면 붙여 쓸 수 있다 (`좀더`)
 *  - **제47항** — 보조용언은 `-아/-어` 뒤에서 붙여 쓸 수 있다 (`괜찮아보이다`, `쌓여있다`)
 *  - **명사 연쇄** — 사전에 없는 `명사+명사`는 띄어 씀이 원칙이나 붙여 쓰는 관행이 굳었다 (`약속시간`)
 */

