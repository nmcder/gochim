/* ── 명사 연쇄 ──────────────────────────────────────────────── */

/**
 * 사전에 표제어가 없는 `명사 + 시간`.
 *
 * 명사와 명사는 각각의 단어라 띄어 씀이 원칙이다(제2항). 그러나 이런 자유 결합은
 * 붙여 쓰는 관행이 흔해 처음에는 경고로 두었다. **오류로 올렸다.**
 * 이 파일의 다른 규칙들과 사정이 다르기 때문이다. `좀더·둘다`는 단음절 단어가 이어질 때
 * 붙여 쓸 수 있다는 제46항이 걸쳐 있어 규정이 실제로 허용하지만, `약속시간`에는
 * 걸칠 조항이 없다. 두 낱말을 붙여 쓴 것일 뿐이라 제2항에 따라 그냥 틀린 표기다.
 * 관행이 흔하다는 것은 자주 틀린다는 뜻이지 허용된다는 뜻이 아니다.
 *
 * 그래서 **표제어가 아님을 하나하나 확인한 것만** 목록에 올린다.
 * `점심시간·근무시간·대기시간`은 사전에 올라 있어 붙여 쓰는 것이 **맞다.** 넣으면 안 된다.
 */
export const myeongsaSigan = defineLexicon({
  id: 'myeongsa-sigan',
  category: 'spacing',
  severity: 'error',
  confidence: 0.88,
  entries: (
    [
      ['약속시간', '약속 시간'],
      ['도착시간', '도착 시간'],
      ['출발시간', '출발 시간'],
      ['마감시간', '마감 시간'],
      ['회의시간', '회의 시간'],
      ['상영시간', '상영 시간'],
      ['영화시간', '영화 시간'],
      ['수업시간', '수업 시간'],
      ['시험시간', '시험 시간'],
      ['배송시간', '배송 시간'],
      ['대기시간', '대기 시간'],
    ] as const
  ).map(([wrong, right]) => ({
    wrong,
    right,
    atWordStart: true,
    message: `'${right}'으로 띄어 씁니다.`,
    explain: `'${wrong}'은 표준국어대사전 표제어가 아닙니다. 명사와 명사는 각각의 단어이므로 띄어 씁니다. 붙여 쓰는 관행이 흔하지만 규정이 허용하는 표기는 아닙니다. 사전에 한 낱말로 오른 '점심시간·근무시간'은 반대로 붙여 쓰는 것이 맞습니다.`,
    refs: ['한글 맞춤법 제2항'],
    examples: [{ wrong: `${wrong}보다 일찍 도착했다.`, right: `${right}보다 일찍 도착했다.` }],
  })),
})

/* ── 구어체 종결어미 '-구' ──────────────────────────────────── */

const EOMI_NAME: Record<string, string> = { 다: '-다고', 라: '-라고', 냐: '-냐고', 자: '-자고' }

export const gueoGu = defineRule({
  id: 'gueo-gu',
  category: 'spelling',
  severity: 'warning',
  confidence: 0.88,
  // 어미 뒤의 '구'만 잡는다. 대구·연구·항구·문구처럼 낱말 끝의 '구'와 갈라야 한다.
  pattern: /([가-힣])(다|라|냐|자)구(?=["'”’」』]|[.!?…~]|\r?\n|$)/g,
  resolve(ctx) {
    // 문체 제안이라 남의 말을 옮긴 자리에서는 내지 않는다. 겹말 규칙과 같은 기준이다.
    if (insideQuotes(ctx.text, ctx.index)) return null
    const eomi = ctx.match[2] ?? ''
    const name = EOMI_NAME[eomi]
    if (!name) return null
    return {
      suggestions: [`${eomi}고`],
      subId: `${eomi}구`,
      // 매치는 어간 음절까지 세 글자지만 고칠 곳은 뒤 두 글자뿐이다.
      offset: 1,
      length: 2,
      message: `구어에서 쓰는 '-${eomi}구'입니다. 표준 어미는 '${name}'입니다.`,
      explain: `어미 '${name}'를 '-${eomi}구'로 적는 것은 구어의 발음을 그대로 옮긴 표기입니다. 뜻이 흐려지지는 않지만 표준어로 인정되는 형태는 '${name}'뿐이라, 격식을 갖춘 글에서는 '${name}'로 적습니다.`,
      refs: ['표준어 규정 제1항'],
    }
  },
  examples: [
    { wrong: '나는 진짜 미안하다구.', right: '나는 진짜 미안하다고.' },
    { wrong: '알았으니까 너도 그러라구.', right: '알았으니까 너도 그러라고.' },
    { wrong: '너 지금 뭐라구?', right: '너 지금 뭐라고?' },
    { wrong: '내일 같이 밥 먹으러 가자구.', right: '내일 같이 밥 먹으러 가자고.' },
  ],
  counterExamples: [
    '대구 달성군 구지 지역에 산업단지가 들어섰다.',
    '머리말에는 연구 목적만 간단히 적었습니다.',
    '항구 컨테이너 야적장에 화물이 가득 쌓여 있다.',
    '표지판 화살표가 출구 반대쪽을 가리키고 있었다.',
    '회사는 서둘러 자구책을 마련했다.',
    '새로 산 가구를 거실에 배치했다.',
    '지구는 태양 둘레를 돈다.',
    '문구점에서 공책 두 권을 샀다.',
    '서울 강남구에 있는 회사에 다닌다.',
    '실험 기구를 조심해서 다뤄야 한다.',
  ],
})

export const principleRules: Rule[] = [jeom46, bojoAeoAttached, myeongsaSigan, gueoGu]
