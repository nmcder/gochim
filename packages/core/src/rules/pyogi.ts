/** '몇 일'은 어떤 문맥에서도 '며칠'이다. 다만 '일본·일식'처럼 '일'로 시작하는 낱말은 건드리지 않는다. */
export const myeotIlSpaced = defineRule({
  id: 'myeot-il-spaced',
  category: 'spelling',
  confidence: 0.95,
  pattern: /몇[ \t]+일(?!본|식|어|화|왕|류|요)/,
  resolve() {
    return {
      suggestions: ['며칠'],
      message: "'몇 일'은 '며칠'로 붙여 적습니다.",
      explain:
        "'며칠'은 '몇 + 일'로 분석되지 않는 한 단어입니다. 어원이 분명하지 않아 소리대로 적으므로 '몇 일'로 띄어 쓰지도, '몇일'로 붙여 쓰지도 않습니다.",
      refs: ['한글 맞춤법 제27항 [붙임 2]'],
    }
  },
  examples: [
    { wrong: '몇 일만 버티면 된다.', right: '며칠만 버티면 된다.' },
    { wrong: '몇 일 안으로 연락드리겠습니다.', right: '며칠 안으로 연락드리겠습니다.' },
  ],
  counterExamples: ['몇 년 만에 만난 친구다.', '몇 달 동안 준비했다.', '몇 일본 기업이 참여했다.'],
})

