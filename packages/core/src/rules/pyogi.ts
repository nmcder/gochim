export const iyeotdaCopula = defineRule({
  id: 'iyeotda-copula',
  category: 'ending',
  confidence: 0.93,
  pattern: /([가-힣])이였/,
  resolve(ctx) {
    const prev = ctx.match[1] ?? ''
    // 받침이 없으면 '이'가 체언의 일부다 — '아이였다·사이였다'.
    if (!hasFinal(prev)) return null
    const word = /[가-힣]+$/.exec(ctx.text.slice(0, ctx.index + 1))?.[0] ?? ''
    // 아는 명사 뒤에서만 발화한다. '민준이였다·종이였다'를 건드리지 않기 위한 값이다.
    if (!HOST_NOUNS.some((noun) => word.endsWith(noun))) return null
    return {
      suggestions: ['이었'],
      offset: 1,
      length: 2,
      message: "받침 있는 말 뒤에서는 '이었-'으로 적습니다.",
      explain:
        "서술격 조사 '이다'의 과거형은 '이었다'입니다. '였-'은 '이었-'이 모음 뒤에서 줄어든 꼴이라(학교였다) 받침 있는 말 뒤에는 쓰지 않습니다.",
      refs: ['한글 맞춤법 제36항'],
    }
  },
  examples: [
    { wrong: '가장 어려운 일이였다.', right: '가장 어려운 일이었다.' },
    { wrong: '오늘은 아르바이트 첫날이였다.', right: '오늘은 아르바이트 첫날이었다.' },
    { wrong: '그때는 학생이였어요.', right: '그때는 학생이었어요.' },
  ],
  counterExamples: [
    '그때만 해도 나는 어린아이였다.',
    '우리는 오래 알고 지낸 사이였다.',
    '책상 위에 있던 건 종이였다.',
    '그 애 이름이 민준이였다.',
  ],
})

/**
 * '들르다'와 '들리다'.
 *
 * 가게에 잠깐 들어가는 것은 '들르다'라 '들러·들렀다'로 활용한다.
 * '들리다'는 소리가 귀에 닿는 것이라 뜻이 아예 다르다.
 *
 * 두 말이 모두 실재하므로 앞 문맥을 본다 — 장소 명사에 '에'가 바로 붙은 자리만 고친다.
 * 소리가 나는 자리는 '카페에서 들렸다'처럼 '에서'를 쓰므로 이 창에 걸리지 않는다.
 */
const PLACES =
  '카페|까페|커피숍|커피샵|편의점|가게|서점|마트|시장|백화점|식당|음식점|빵집|병원|약국|은행|우체국|도서관|학원|사무실|화장실|주유소|미용실|문구점|휴게소|매장|박물관|미술관|숙소|호텔|본가|고향'

export const deulleuda = defineRule({
  id: 'deulleuda-place',
  category: 'confusable',
  confidence: 0.88,
  // '들려주다·들려오다'는 '들리다'의 사동·복합형이라 뒤 음절로 걸러 낸다.
  pattern: new RegExp(`(?:${PLACES})에[ \t]*들(렸|려)(?![주줬준줄오왔온올려])`),
  resolve(ctx) {
    const tail = ctx.match[1] === '렸' ? '렀' : '러'
    return {
      suggestions: ['들' + tail],
      offset: ctx.match[0].length - 2,
      length: 2,
      message: "잠깐 다녀오는 것은 '들르다'라 '들러·들렀다'로 활용합니다.",
      explain:
        "'들르다'는 '으' 불규칙 용언이라 '들러, 들렀다'가 됩니다. '들리다'는 소리가 귀에 닿거나 병에 걸린다는 뜻의 다른 말입니다.",
    }
  },
  examples: [
    { wrong: '성수동에 있는 카페에 들렸다.', right: '성수동에 있는 카페에 들렀다.' },
    { wrong: '퇴근길에 서점에 들려 책을 샀다.', right: '퇴근길에 서점에 들러 책을 샀다.' },
  ],
  counterExamples: [
    '카페에서 잔잔한 음악이 들렸다.',
    '옆방에서 인기척이 들렸다.',
    '병원에 들러 약을 받아 왔다.',
    '식당에 들려주는 노래가 좋았다.',
  ],
})

export const pyogiRules: Rule[] = [myeotIlSpaced, iyeotdaCopula, deulleuda]
