import { finalOf } from '../hangul.js'
import { defineRule } from './define.js'
import type { Rule } from '../types.js'

/**
 * 갈라진 파생동사를 도로 붙인다 — `이야기 할` → `이야기할`.
 *
 * 이 파일의 규칙은 다른 띄어쓰기 규칙과 **방향이 반대**다. 띄운 것을 붙인다.
 * `이야기하다·공부하다·생각하다`는 표준국어대사전에 한 단어로 오른 동사이고,
 * 접미사 `-하다`는 앞말에 붙여 쓴다.
 *
 * ## 두 관문을 지나야 붙인다
 *
 * **하나, 뒷말이 정말 `하다`의 활용인가.**
 * `하`로 시작하는 낱말은 끝없이 많다(하나·하늘·하루·하필·하객). 그래서 명사를 막는
 * 블록리스트가 아니라 **어미 허용 목록**으로 판정한다. 명사는 늘어나지만 어미는 닫힌 집합이다.
 *
 * **둘, 앞 어절이 관형어인가.**
 * 관형어가 걸리면 그 말은 명사로 쓰인 것이라 띄어 쓰는 게 맞다.
 *
 *   오늘부터 진짜 공부 해야겠다 → 공부해야겠다   (붙인다)
 *   무슨 생각 하니              → 그대로         (관형사 '무슨')
 *   어제 한 약속 하나           → 그대로         (관형사형 어미 '-ㄴ')
 *
 * 매치는 어미 끝까지 물지만 고칠 곳은 `명사 + 공백 + 하`뿐이다. `length`를 주지 않으면
 * `공부 해야겠다`가 통째로 치환 구간이 되어 밑줄이 문장을 뒤덮는다.
 */

/** 표준국어대사전에 `X하다`가 한 단어로 올라 있는 서술성 명사. 실제 글에서 잦은 것만 담는다. */
const HADA_NOUNS = [
  '이야기', '공부', '생각', '사랑', '운동', '요리', '청소', '연습', '준비', '노력',
  '후회', '걱정', '고민', '약속', '인사', '대답', '질문', '부탁', '이해', '기억',
  '감사', '도착', '출발', '시작', '실수', '소개', '정리', '산책', '대화', '운전',
]

/** `하-` 뒤에 올 수 있는 어미의 첫 음절. 없으면 하나·하늘·하루·하필·하객·하락이다. */
const AFTER_HA = new Set([
  '고', '기', '는', '니', '다', '더', '던', '도', '되', '든', '느', '냐', '네',
  '려', '러', '래', '며', '면', '자', '지', '죠', '게', '겠', '세', '시', '십',
  '신', '실', '셨', '였', '잖',
])
/** `할-` 뒤. 없으면 할머니·할아버지·할인·할부·할당이다. */
const AFTER_HAL = new Set(['까', '게', '래', '지', '수', '걸', '텐', '듯', '망', '뿐'])
/** `해-` 뒤. 없으면 해외·해결·해변·해바라기다. */
const AFTER_HAE = new Set(['서', '도', '야', '라', '요', '주', '줘', '줬', '준', '줄', '봐', '봤', '본', '보', '선'])
/** 허용 음절을 통과하지만 `하다`의 활용이 아닌 말. 여기만 블록리스트로 막는다. */
const NOT_HADA = new Set(['하도', '하지만', '하기야', '하다못해', '하도급', '하다하다', '하기는커녕'])
/** `합-`은 합격·합의·합창·합숙과 겹친다. 어미가 확실한 것만 받는다. */
const HAP_OK = new Set(['합니다', '합니까', '합시다', '합디다'])

/**
 * 앞에 오면 뒷말이 **명사**로 쓰인 것이라 붙이면 안 되는 말.
 *
 * 받침이 ㄴ·ㄹ인 관형사(무슨·어떤·모든)는 아래 관형사형 어미 판정에 함께 걸리므로
 * 여기에는 **받침으로 걸러지지 않는 것**만 적는다. 대명사의 관형격(내·제·우리)도 넣는다.
 */
const ADNOMINALS = new Set([
  '그', '이', '저', '요', '여러', '아무', '어느', '온갖', '새', '각', '매', '몇',
  '첫', '옛', '두', '세', '네', '다섯', '여섯', '별의별', '단', '총', '뭔', '웬',
  '내', '제', '자기', '우리', '저희', '남', '걔', '얘', '쟤', '딴', '뭇',
])

export const seosulHada = defineRule({
  id: 'seosul-hada',
  category: 'spacing',
  confidence: 0.9,
  pattern: new RegExp(`(?<![가-힣])(${HADA_NOUNS.join('|')}) (하|한|할|했|해|함|합)([가-힣]*)`, 'g'),
  resolve(ctx) {
    const noun = ctx.match[1] ?? ''
    const head = ctx.match[2] ?? ''
    const rest = ctx.match[3] ?? ''
    const tail = head + rest
    const next = rest.slice(0, 1)

    // ── 뒷말이 정말 '하다'의 활용인가 ──
    if (NOT_HADA.has(tail)) return null
    if (head === '하') {
      if (!AFTER_HA.has(next)) return null
      // '하느라'와 '하느님'을 가른다.
      if (next === '느' && !/^하느(라|냐)/.test(tail)) return null
    } else if (head === '할') {
      if (next && !AFTER_HAL.has(next)) return null
    } else if (head === '해') {
      if (next && !AFTER_HAE.has(next)) return null
    } else if (head === '한') {
      // 맨 '한'은 수관형사다 — '생각 한 번', '질문 한 개'. '한다-'만 받는다.
      if (next !== '다') return null
    } else if (head === '합') {
      if (!HAP_OK.has(tail)) return null
    } else if (head !== '했') {
      // '함'은 '함께·함부로·함박눈'과 겹쳐 이득이 없다. 통째로 버린다.
      return null
    }

    // ── 앞 어절이 관형어면 '명사 + 본용언 하다'라 두 단어다 ──
    const words = ctx.text.slice(0, ctx.index).split(/[ \t]/)
    const prev = words.length >= 2 ? (words[words.length - 2] ?? '') : ''
    if (prev) {
      if (ADNOMINALS.has(prev)) return null
      // 관형격 조사 '의' — '친구의 부탁', '남의 이야기'.
      if (prev.endsWith('의')) return null
      // 관형사형 어미 -ㄴ/-은/-는/-던, -ㄹ/-을. 문자열에서는 종성 ㄴ·ㄹ로 드러난다.
      const fin = finalOf(prev.slice(-1))
      if (fin === 'ㄴ' || fin === 'ㄹ') return null
    }
    // '몇 마디 대화 하다'처럼 관형사가 한 어절 더 앞에 있을 수도 있다.
    const prev2 = words.length >= 3 ? (words[words.length - 3] ?? '') : ''
    if (prev2 && ADNOMINALS.has(prev2)) return null

    // 오류 구간을 **명사의 끝 음절과 공백**으로 좁힌다.
    //
    // `이야기 할수있었던건`처럼 뒤엣말도 틀린 자리가 흔하다. 구간을 `이야기 할`까지 잡으면
    // 확신도가 더 높은 nnb-su(`할수있` → `할 수 있`)와 겹쳐 둘 중 하나가 통째로 묻힌다.
    // 공백 앞쪽으로 물러나면 두 진단이 각자 자리를 차지해 한 번에 다 고쳐진다.
    // 공백 한 칸만 잡으면 밑줄이 보이지 않으므로 앞 음절을 한 자 포함한다.
    return {
      offset: noun.length - 1,
      length: 2,
      suggestions: [noun.slice(-1)],
      subId: noun,
      message: `'${noun}하다'는 한 단어입니다. 붙여 씁니다.`,
      explain: `'${noun}하다'는 표준국어대사전에 한 단어로 오른 말입니다. 접미사 '-하다'는 앞말에 붙여 씁니다. 다만 앞에 관형어가 오면 '${noun}'이 명사로 쓰인 것이라 띄어 씁니다 — '무슨 ${noun} 하니'.`,
      refs: ['한글 맞춤법 제2항'],
    }
  },
  examples: [
    { wrong: '친구와 오래 이야기 할 수 있었던 하루였다.', right: '친구와 오래 이야기할 수 있었던 하루였다.' },
    { wrong: '오늘부터 진짜 공부 해야겠다.', right: '오늘부터 진짜 공부해야겠다.' },
    { wrong: '너무 걱정 하지 마세요.', right: '너무 걱정하지 마세요.' },
    { wrong: '매일 아침 운동 하고 있어요.', right: '매일 아침 운동하고 있어요.' },
    { wrong: '도와주셔서 감사 합니다.', right: '도와주셔서 감사합니다.' },
    { wrong: '시험 준비 하느라 바빴다.', right: '시험 준비하느라 바빴다.' },
    { wrong: '혼자 산책 하러 나갔다.', right: '혼자 산책하러 나갔다.' },
    { wrong: '아까 뭐라고 대답 했더라?', right: '아까 뭐라고 대답했더라?' },
    { wrong: '나중에 후회 할 것 같아.', right: '나중에 후회할 것 같아.' },
    { wrong: '어제 친구랑 대화 했다.', right: '어제 친구랑 대화했다.' },
  ],
  counterExamples: [
    '무슨 생각 하니?',
    '이 공부 하기 싫다.',
    '숙제 할 일이 많다.',
    '질문 하나만 해도 될까요?',
    '부탁 하나만 들어줘.',
    '생각 한 번 해 봐.',
    '어떤 준비 하고 있니?',
    '여러 고민 하다 결정했다.',
    '온갖 걱정 하지 않아도 된다.',
    '내 생각 하지 말고 네 일이나 해.',
    '자기 생각 하기에 바쁘다.',
    '정리 하나도 안 됐다.',
    '공부 하루도 안 쉬었다.',
    '연습 할인 쿠폰을 받았다.',
    '준비 함께 하자.',
    '생각 하도 많아서 잠이 안 온다.',
    '인사 한마디 없이 가 버렸다.',
    '실수 한 번쯤은 괜찮아.',
    '출발 하루 전에 짐을 쌌다.',
    '몇 마디 대화 하다 말았다.',
    '그 일 하지 마.',
    '청소 안 하고 나가 버렸다.',
    '운동 한 시간 하고 왔다.',
    '모든 연습 하고 나서 쉬었다.',
    '친구의 부탁 하나를 들어줬다.',
    '대화 하지만 통하지 않았다.',
    '기억 하나둘씩 떠올랐다.',
    '약속 한 번도 어긴 적 없다.',
    '연습 합숙을 다녀왔다.',
  ],
})

export const seosulHadaRules: Rule[] = [seosulHada]
