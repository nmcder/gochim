/**
 * 명사·부사 뒤에 붙어 버린 부사 `좀`.
 *
 * `좀`은 `조금`의 준말인 부사라 앞말과 띄어 쓴다. 그런데 `좀`으로 **끝나는** 표제어가
 * 서른두 개나 된다(나무좀·가루좀·가위좀·감나무좀·개나무좀…). 전부 벌레 이름이라
 * "앞말 + 좀"을 통째로 잡으면 이것들이 갈라진다. 그래서 **앞말을 낱개로 적어 둔다.**
 *
 * 여기 적은 앞말은 모두 표준국어대사전에서 `앞말 + 좀` 형태를 검색해 0건임을 확인했다.
 *
 * ## 단음절 앞말과 제46항
 *
 * `물 좀`처럼 단음절끼리 이어지면 제46항의 붙여쓰기 허용이 떠오른다. 그러나 제46항은
 * "의미적으로 자연스럽게 한 덩이를 이룰 수 있는" 자리에만 적용된다. 국립국어원은
 * `더 못 가`를 `더못 가`로 붙일 수 없는 이유로 "'못'이 뒷말을 먼저 꾸미므로 앞말과
 * 묶이기 어렵다"를 들었다. `물 좀 줘`의 `좀`도 뒤의 `줘`를 꾸미므로 앞말과 묶이지 않는다.
 */
const JOM_HEAD =
  '시간|잠깐|잠시|이거|그거|저거|이것|그것|여기|저기|거기|전화|연락|정신|부탁|사진|자리|얘기|이야기|청소|숙제|확인|대답|생각|정리|양보|조심|조용히|빨리|천천히|그만|이제|제발|물|밥|돈|말'

