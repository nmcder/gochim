import { insideQuotes } from '../protect.js'
import { defineRule } from './define.js'
import type { Rule } from '../types.js'

/**
 * 구어체 종결·연결 어미 `-구`.
 *
 * 표준 어미는 `-고`다. `-다구·-라구·-냐구·-자구`는 서울말 구어의 발음을 그대로 옮긴 표기라
 * 표준어로 인정되지 않는다. 다만 **틀린 글이라기보다 문체 선택**에 가까워 `warning`으로 알리기만 한다.
 * 겹말(`pleonasm-*`)과 같은 자리다.
 *
 * ## `구`를 어미로 볼 수 있는 자리
 *
 * `구`는 낱말 속에 지천으로 널려 있다 — 대구·연구·친구·도구·기구·가구·지구·항구·출구·탐구·문구.
 * 그래서 두 겹으로 막는다.
 *
 *  - **앞을 본다.** 어미로 쓰인 `-구`는 `다/라/냐/자` 뒤에만 온다. 게다가 그 앞에 한글 음절이
 *    하나 더 있어야 한다(어간이 있어야 어미가 붙는다). 이 조건 하나로 위 낱말이 전부 떨어지고,
 *    유일하게 걸릴 뻔한 `자구(自救/字句)`도 어절 첫머리에 오므로 함께 떨어진다.
 *  - **뒤를 본다.** 문장이 거기서 끝날 때만 잡는다.
 *
 * 뒤를 보는 조건이 왜 필요한가. 문장 한가운데의 `-다구`는 남의 말이나 자기 말을 **옮기는** 자리인
 * 경우가 대부분이고(`진짜 미안하다구 계속 사과를 했다`), 그 자리는 이 저장소의 실문 정답셋이
 * "발화의 어조를 그대로 적은 의도적 구어 표기"로 보아 고치지 않기로 이미 판단한 곳이다.
 * 문장 끝의 `-구`는 글쓴이 자신의 종결 어미라 그런 여지가 없다.
 *
 * ## 매치 구간과 고치는 구간이 다르다
 *
 * 패턴은 어간 음절을 하나 더 먹는다 — 그래야 어미인지 판정할 수 있다.
 * 고칠 것은 뒤 두 글자(`다구` → `다고`)뿐이라 `offset`/`length`로 구간을 좁힌다.
 */

/** 어미별로 사용자에게 보여 줄 이름. */
const EOMI_NAME: Record<string, string> = {
  다: '-다고',
  라: '-라고',
  냐: '-냐고',
  자: '-자고',
}

export const gueoGu = defineRule({
  id: 'gueo-gu',
  category: 'ending',
  severity: 'warning',
  confidence: 0.88,
  pattern: /([가-힣])(다|라|냐|자)구(?=["'”’」』]|[.!?…~]|\r?\n|$)/g,
  resolve(ctx) {
    // 문체 제안이라 남의 말을 옮긴 자리에서는 내지 않는다. (겹말 규칙과 같은 기준)
    if (insideQuotes(ctx.text, ctx.index)) return null
    const eomi = ctx.match[2] ?? ''
    const name = EOMI_NAME[eomi]
    if (!name) return null
    return {
      suggestions: [`${eomi}고`],
      subId: `${eomi}구`,
      // 매치는 어간 음절까지 3글자지만 고칠 곳은 뒤 두 글자뿐이다.
      offset: 1,
      length: 2,
      message: `구어에서 쓰는 '-${eomi}구'입니다. 표준 어미는 '-${eomi}고'입니다.`,
      explain: `어미 '${name}'를 '-${eomi}구'로 적는 것은 구어의 발음을 그대로 옮긴 표기입니다. 뜻이 흐려지지는 않지만 표준어로 인정되는 형태는 '${name}'뿐이라, 격식을 갖춘 글에서는 '${name}'로 적습니다.`,
      refs: ['표준어 규정 제1항'],
    }
  },
  examples: [
    { wrong: '나는 진짜 미안하다구.', right: '나는 진짜 미안하다고.' },
    { wrong: '알았으니까 너도 그러라구.', right: '알았으니까 너도 그러라고.' },
    { wrong: '너 지금 뭐라구?', right: '너 지금 뭐라고?' },
    { wrong: '내일 같이 밥 먹으러 가자구.', right: '내일 같이 밥 먹으러 가자고.' },
    { wrong: '도대체 왜 그러냐구?', right: '도대체 왜 그러냐고?' },
    { wrong: '이건 내 거라구!', right: '이건 내 거라고!' },
  ],
  counterExamples: [
    '대구 달성군 구지 지역에 대규모 산업단지가 들어섰다.',
    '머리말에는 연구 목적만 간단히 적었습니다.',
    '항구 컨테이너 야적장에 화물이 가득 쌓여 있다.',
    '표지판 화살표가 출구 반대쪽을 가리키고 있었다.',
    '제1회 교내 과학 탐구 대회에서 금상을 받았습니다.',
    '어제 친구랑 영화를 봤다.',
    '회사는 서둘러 자구책을 마련했다.',
    '계약서 자구를 몇 군데 다듬었다.',
    '새로 산 가구를 거실에 배치했다.',
    '지구는 태양 둘레를 돈다.',
    '문구점에서 공책 두 권을 샀다.',
    '서울 강남구에 있는 회사에 다닌다.',
    '실험 기구를 조심해서 다뤄야 한다.',
    '나는 진짜 미안하다구 계속 사과를 했다.',
  ],
})

export const gueoRules: Rule[] = [gueoGu]
