import { finalOf } from '../hangul.js'
import { defineRule } from './define.js'
import type { Rule } from '../types.js'

/**
 * 의존명사 `거/건/걸` 뒤에 조사나 어미가 더 붙은 꼴.
 *
 * [nnbGeotBare](./spacing-prose.ts)는 패턴 끝이 `(?![가-힣])`라 뒤에 한글이 더 오면 포기한다.
 * `없는거고`처럼 조사나 어미가 이어 붙은 자리를 통째로 놓치고 있었다.
 *
 * `거`는 자립명사 속에 워낙 흔해서(자전거·설거지·거울·거의·근거·증거) 앞 음절만으로는
 * 가를 수 없다. 그래서 두 규칙 모두 **앞말이 관형사형인지**를 먼저 묻는다.
 *
 *   ㄴ 계열 (-는/-은/-던/-ㄴ)  → 뒤의 `거·건·걸`은 의존명사
 *   ㄹ 계열 (-ㄹ/-을)          → `거`만 의존명사. `게·걸`은 어미다(할게·참을걸)
 *
 * 뒤에 붙은 조사·어미는 건드리지 않는다. `없는거고`에서 고칠 것은 `는거`뿐이고
 * `고`는 그대로 둔다. 그래서 `offset`/`length`로 구간을 두 음절로 좁힌다.
 */

/** 관형사형 어미 `-는/-은/-던`과 관형사형 `-ㄴ` 꼴. */
const ADNOMINAL_N = '는|은|던|한|인|된|런|떤'
/** `거` 뒤에 이어 붙는 조사·어미. 긴 것을 앞에 두어야 `지만`이 `지`에 먹히지 않는다. */
const GEO_TAIL = '예요|에요|였|니까|잖|라고|라는|라도|지만|지요|고|다|지|야|네|군|죠|라'

export const nnbGeoAttached = defineRule({
  id: 'nnb-geo-attached',
  category: 'spacing',
  confidence: 0.93,
  pattern: new RegExp(`(${ADNOMINAL_N})(?:(거)(?:${GEO_TAIL})|(건)(?:데|지|가)|(걸)로)`, 'g'),
  resolve(ctx) {
    const prev = ctx.match[1] ?? ''
    // 세 갈래 중 하나만 잡힌다 — 거 / 건 / 걸.
    const noun = ctx.match[2] ?? ctx.match[3] ?? ctx.match[4] ?? ''
    if (!noun) return null

    // `은거(隱居)`만은 열거 목록을 뚫는다. 관형사형 `-은`은 반드시 어간 뒤에 오므로
    // 어절 첫머리의 `은`은 어미가 아니다 — `은거지에서` ≠ `은 거지에서`.
    if (prev === '은' && !/[가-힣]/.test(ctx.before)) return null

    const explain =
      noun === '거'
        ? "'거'는 '것'을 구어적으로 이르는 의존명사입니다. 뒤에 조사나 어미가 더 붙어도 앞의 관형사형과는 띄어 씁니다."
        : noun === '건'
          ? "'건'은 '것은'이 줄어든 말입니다. 의존명사 '거'가 들어 있으므로 관형사형과 띄어 씁니다."
          : "'걸'은 '것을'이 줄어든 말입니다. 의존명사 '거'가 들어 있으므로 관형사형과 띄어 씁니다."

    return {
      suggestions: [`${prev} ${noun}`],
      subId: noun,
      // 뒤에 붙은 조사·어미(`거고`의 `고`, `건데`의 `데`)는 그대로 두고 두 음절만 가른다.
      offset: 0,
      length: 2,
      message: `의존명사 '${noun}'은 앞말과 띄어 씁니다.`,
      explain,
      refs: ['한글 맞춤법 제42항'],
    }
  },
  examples: [
    { wrong: '애초에 방법이 없는거고 내 탓도 아니다.', right: '애초에 방법이 없는 거고 내 탓도 아니다.' },
    { wrong: '다들 그렇게 하는거지 뭐.', right: '다들 그렇게 하는 거지 뭐.' },
    { wrong: '어제 먹은건데 아직 남았다.', right: '어제 먹은 건데 아직 남았다.' },
    { wrong: '예전에 하던거라 손에 익었다.', right: '예전에 하던 거라 손에 익었다.' },
    { wrong: '제 말이 맞는거예요.', right: '제 말이 맞는 거예요.' },
    { wrong: '점심은 그냥 먹는걸로 하자.', right: '점심은 그냥 먹는 걸로 하자.' },
    { wrong: '처음부터 잘못된거고 지금도 그렇다.', right: '처음부터 잘못된 거고 지금도 그렇다.' },
    { wrong: '이게 정상인건지 모르겠다.', right: '이게 정상인 건지 모르겠다.' },
    { wrong: '그런거야 나도 안다.', right: '그런 거야 나도 안다.' },
    { wrong: '그래서 이렇게 된거네.', right: '그래서 이렇게 된 거네.' },
    { wrong: '어떤걸로 할지 못 정했다.', right: '어떤 걸로 할지 못 정했다.' },
  ],
  counterExamples: [
    '내가 먼저 할게.',
    '그때 참을걸 그랬다.',
    '동생 자전거를 고쳤다.',
    '설거지를 하고 나왔다.',
    '근거를 대라.',
    '오늘 안건은 세 가지다.',
    '다음 달이 선거고 그다음이 개표다.',
    '인건비가 크게 올랐다.',
    '그는 산속에 은거하며 지냈다.',
    '은거지에서 여생을 보냈다.',
    '거의 다 왔다.',
    '거울을 보며 웃었다.',
    '뜨거운 물에 데었다.',
    '즐거운 하루였다.',
    '오늘은 날씨가 좋은걸.',
    '하건 말건 마음대로 해.',
    '천거한 사람이 누구냐.',
    '게다가 비까지 왔다.',
    '런던 거리를 걸었다.',
    '이건 네 거야.',
    '별거 아니야.',
    '논란이 불거지고 말았다.',
    '알거지가 되었다.',
    '증거가 부족하다.',
    '연거푸 세 번이나 넘어졌다.',
    '단거리 달리기에 나갔다.',
  ],
})

/** ㄹ받침 뒤의 `거`와 붙어 한 낱말이 되는 앞 음절 — 설거지·별거·불거지다·알거지·물거품·벌거숭이. */
const L_GEO_WORDS = new Set(['설', '별', '불', '알', '물', '벌'])
/** nnb-geo가 이미 보는 어미는 뺐다. `지`는 설거지·알거지·불거지다 때문에 넣지 않는다. */
const GEO_TAIL_L = '잖|다|네|군|죠'

export const nnbGeoLAttached = defineRule({
  id: 'nnb-geo-l-attached',
  category: 'spacing',
  confidence: 0.9,
  pattern: new RegExp(`([가-힣])거(?:${GEO_TAIL_L})`, 'g'),
  resolve(ctx) {
    const prev = ctx.match[1] ?? ''
    // 관형사형 어미 -ㄹ/-을 뒤에서만 본다. 그 밖의 ㄹ받침은 낱말 속일 뿐이다.
    if (finalOf(prev) !== 'ㄹ') return null
    if (L_GEO_WORDS.has(prev)) return null
    return {
      suggestions: [`${prev} 거`],
      offset: 0,
      length: 2,
      message: "의존명사 '거'는 앞말과 띄어 씁니다.",
      explain:
        "'거'는 '것'의 구어형 의존명사입니다. '-ㄹ게·-ㄹ걸'과 달리 '-ㄹ거'라는 어미는 없으므로, 관형사형 어미 '-ㄹ' 뒤의 '거'는 언제나 의존명사입니다.",
      refs: ['한글 맞춤법 제42항'],
    }
  },
  examples: [
    { wrong: '어차피 나중에 할거잖아.', right: '어차피 나중에 할 거잖아.' },
    { wrong: '내일이면 다 끝날거다.', right: '내일이면 다 끝날 거다.' },
    { wrong: '그 친구도 같이 갈거죠?', right: '그 친구도 같이 갈 거죠?' },
  ],
  counterExamples: [
    '내가 이따가 다시 전화할게.',
    '그때 조금만 더 참을걸.',
    '설거지도 안 하고 나갔다.',
    '논란이 불거지자 말을 아꼈다.',
    '알거지가 될 뻔했다.',
    '물거품이 되었다.',
    '벌거벗은 임금님 이야기.',
    '별거 아니라니까.',
    '먹을거리가 풍성하다.',
    '볼거리가 많은 도시다.',
    '읽을거리를 챙겼다.',
    '출렁거리는 물결을 보았다.',
  ],
})

export const nnbGeoRules: Rule[] = [nnbGeoAttached, nnbGeoLAttached]
