/**
 * 앞 문맥에 특정 말이 있을 때만 발화하게 하는 가드.
 *
 * 혼동어는 두 표기가 모두 실재하므로 단어만 보고는 판정할 수 없다.
 * `낳으세요`가 오류인지(병이 낫다) 정상인지(아이를 낳다)는 앞 문맥이 정한다.
 * 형태소 층이 붙기 전까지는 이 창(window)이 우리가 가진 유일한 문맥이다.
 */
const near = (re: RegExp, window = 16) => (ctx: RuleContext) =>
  re.test(ctx.text.slice(Math.max(0, ctx.index - window), ctx.index))

