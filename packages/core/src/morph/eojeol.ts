interface Cut {
  at: number
  kind: Kind
  /** 갈라 낸 말. 메시지에 그대로 쓴다. */
  word: string
}

/**
 * 관형사형 어미 + 한 글자가 **어미 하나로도 읽히는** 꼴.
 *
 * 분석기가 문맥에 따라 읽기를 바꾼다. 같은 `주는데`를 어떤 문장에서는
 * `주/VX + 는데/EC`(연결어미)로, 어떤 문장에서는 `주/VV + 는/ETM + 데/NNB`(의존명사)로
 * 읽는다. 뒤엣것을 믿고 가르면 **연결어미 `-는데`가 통째로 깨진다.**
 * 어미는 닫힌 집합이라 여기서는 목록이 정답이다.
 *
 * 1층의 `nnb-de-josa`도 같은 이유로 `-은데/-ㄴ데`를 통째로 포기하고 있다.
 */
const EOMI_LOOKALIKE = new Set([
  '는데', '은데', '던데',
  '는가', '은가', '던가',
  '는지', '은지', '던지', '을지', '을까',
])

/**
 * 그중 **뒤에 조사가 붙으면** 어미로는 설명이 안 되는 것.
 *
 * 어미 뒤에는 조사가 못 오므로 `모으는데에`의 `데`는 의존명사가 맞다.
 * 이 빠져나갈 길이 `데`에만 있는 이유는, `-은가·-는지`는 명사절이 되어
 * 조사를 달 수 있기 때문이다 — `같은가를 잰다`, `가는지를 물었다`.
 */
const DE_LIKE = new Set(['는데', '은데', '던데'])

/** 이 자리에서 어절을 갈라야 하는가. 갈래를 돌려주고, 아니면 null. */
function cutKind(word: Word, i: number): Kind | null {
  const prev = word.morphemes[i - 1]!
  const cur = word.morphemes[i]!

  if (prev.pos === 'ETM' && EOMI_LOOKALIKE.has(prev.text + cur.text)) {
    const next = word.morphemes[i + 1]
    if (!DE_LIKE.has(prev.text + cur.text) || !next || !isJosa(next.pos)) return null
  }

  if (cur.pos === 'NNB') {
    // 수 + 단위명사는 붙여 쓸 수 있다 — `10년`, `90점`, `3개`. (제43항 다만)
    if (prev.pos === 'SN' || /^\d/.test(word.text)) return null
    // 단위명사인데 앞에 수가 없으면 단위로 쓰인 것이 아니다. ('여명'을 '여 명'으로 쪼개는 오분석 방지)
    if (UNIT_NNB.has(cur.text) && !['SN', 'NR', 'MM'].includes(prev.pos)) return null
    if (NOT_REALLY_NNB.has(cur.text)) return null
    if (NNB_OR_JOSA.has(cur.text) && CHEEON.has(prev.pos)) return null
    // `그분·이분·저분·윗분·여러분`은 관형사와 붙어 한 낱말이 된 말이다.
    if (cur.text === '분' && prev.pos === 'MM') return null
    return 'nnb'
  }

  if (isJosa(prev.pos) && VERBAL.has(cur.pos)) return 'josa'
  if (prev.pos === 'ETM' && FREE_NOUN.has(cur.pos)) return 'etm'

  if (FREE_NOUN.has(prev.pos) && VERBAL.has(cur.pos)) {
    // 한 음절 명사는 분석기가 짐작으로 만들어 낸 것일 때가 많다 — `누우세요`를 `누/NNG + 울/VV`로 읽었다.
    if (prev.text.length < 2) return null
    // 어간의 첫머리만 본다 — `확인해보니까`의 `해보`처럼 활용형이 이어 붙어 나오기도 한다.
    if (NOUN_KEEP_STEM.some((stem) => cur.text.startsWith(stem))) return null
    return 'noun'
  }

  if (prev.pos === 'MAG' && SPLIT_ADVERBS.has(prev.text)) {
    if (KEEP_JOINED_PAIR.has(`${prev.text}+${cur.text}`)) return null
    if (VERBAL.has(cur.pos)) {
      if (ADVERB_KEEP_STEM.has(cur.text) && !ADVERB_HADA_OK.has(prev.text)) return null
      return 'adverb'
    }
    // 부사 뒤의 부사·명사도 별개의 단어다 — `제일먼저`, `다시한번`, `일찍예매했는데`.
    if (cur.pos === 'MAG' && (SPLIT_ADVERBS.has(cur.text) || TAIL_ADVERBS.has(cur.text))) return 'adverb'
    if (cur.pos === 'NNG') return 'adverb'
  }

  // 종결어미(EF)로 읽히는 자리도 있다 — `아프신가봐`의 `ㄴ가`가 그렇다.
  if ((prev.pos === 'EC' || prev.pos === 'EF') && SPACED_EC.has(prev.text)) {
    if (cur.pos === 'VX') return 'bojo'
    if (cur.pos === 'VV' && AUX_STEM.has(cur.text)) return 'bojo'
  }

  // 접미사 뒤에 명사가 바로 붙은 자리 — `선생님덕분에`, `학생들대표`.
  // 접미사는 앞말에 붙지만 그다음 명사는 별개의 단어다.
  if (prev.pos === 'XSN' && cur.pos === 'NNG') return 'noun'

  return null
}

/**
 * 잘라 낸 뒤 조각이 너무 짧으면 오분석을 의심한다.
 *
 * `앞에서`를 `앞/NNG + 에/JKB + 서/VV`로 읽어 `앞에 서`로 가른 자리가 있었다.
 * 홀로 선 용언은 어미가 붙어 두 글자를 넘는다. 다만 **의존명사와 보조용언은
 * 한 글자로도 선다** — `할 수`, `들릴까 봐`. 그래서 갈래마다 기준이 다르다.
 */
function minTail(kind: Kind): number {
  // 의존명사·보조용언은 한 글자로도 선다(`할 수`, `들릴까 봐`).
  // 관형사형 뒤의 명사도 마찬가지다 — `확인한 뒤`, `지나온 길`.
  return kind === 'josa' || kind === 'adverb' || kind === 'noun' ? 2 : 1
}

